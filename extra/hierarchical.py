# STABLE QDRANT ID
# ============================================================

_ID_NAMESPACE = uuid.UUID(
    "6f1a2e2a-9b1a-4c8e-8f0a-6b6a2e2a9b1a"
)


def stable_id(logical_id: str) -> str:
    """
    Convert application grandchild_id into a deterministic UUID.

    This means:
        same grandchild_id -> same Qdrant point ID

    Re-running ingestion therefore updates existing vectors
    instead of generating another copy.
    """

    return str(
        uuid.uuid5(
            _ID_NAMESPACE,
            str(logical_id),
        )
    )


# ============================================================
# BASIC VALIDATION
# ============================================================

def safe_string(value) -> str:
    if value is None:
        return ""

    return str(value).strip()


def validate_grandchild(chunk: dict, index: int):
    required_fields = [
        "grandchild_id",
        "parent_id",
        "source",
        "title",
        "heading",
        "type",
        "content",
        "embedding_text",
    ]

    missing = [
        field
        for field in required_fields
        if field not in chunk
    ]

    if missing:
        raise ValueError(
            f"Grandchild #{index} is missing fields: {missing}"
        )

    if not safe_string(chunk["grandchild_id"]):
        raise ValueError(
            f"Grandchild #{index} has empty grandchild_id."
        )

    if not safe_string(chunk["parent_id"]):
        raise ValueError(
            f"Grandchild #{index} has empty parent_id."
        )

    if not safe_string(chunk["content"]):
        raise ValueError(
            f"Grandchild #{index} has empty content."
        )

    if not safe_string(chunk["embedding_text"]):
        raise ValueError(
            f"Grandchild #{index} has empty embedding_text."
        )


