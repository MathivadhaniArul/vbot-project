class RemoteBGEM3Embeddings(Embeddings):
    """
    Calls the local BGE-M3 embedding server.

    Documents:
        passage: <text>

    Queries:
        query: <text>
    """

    def __init__(
        self,
        url: str,
        batch_size: int = 4,
        max_retries: int = 3,
        backoff_base: float = 2.0,
    ):
        self.url = url.rstrip("/")
        self.batch_size = batch_size
        self.max_retries = max_retries
        self.backoff_base = backoff_base

    def _post_with_retry(self, payload):
        last_exc = None

        for attempt in range(self.max_retries):
            try:
                response = requests.post(
                    f"{self.url}/embed",
                    json=payload,
                    timeout=300,
                )

                response.raise_for_status()

                data = response.json()

                if "embeddings" not in data:
                    raise ValueError(
                        "Embedding server response does not contain "
                        "'embeddings'."
                    )

                return data

            except (requests.RequestException, ValueError) as exc:
                last_exc = exc

                if attempt < self.max_retries - 1:
                    sleep_seconds = self.backoff_base ** attempt

                    print(
                        f"  Embedding request failed: {exc!r}"
                    )
                    print(
                        f"  Retrying in {sleep_seconds:.1f}s "
                        f"[attempt {attempt + 1}/{self.max_retries}]"
                    )

                    time.sleep(sleep_seconds)

        raise RuntimeError(
            f"Embedding request failed after "
            f"{self.max_retries} attempts: {last_exc}"
        ) from last_exc

    def embed_documents(self, texts: List[str]) -> List[List[float]]:
        """
        Embed grandchild embedding_text values.

        IMPORTANT:
        No filtering occurs here.

        The returned embeddings remain in exactly the same
        positional order as the supplied texts.
        """

        if not texts:
            return []

        prepared_texts = [
            f"passage: {str(text).strip()}"
            for text in texts
        ]

        embeddings = []

        total = len(prepared_texts)

        for start in range(0, total, self.batch_size):
            batch = prepared_texts[
                start:start + self.batch_size
            ]

            data = self._post_with_retry({
                "texts": batch
            })

            batch_embeddings = data["embeddings"]

            if len(batch_embeddings) != len(batch):
                raise RuntimeError(
                    "Embedding server returned an unexpected number "
                    f"of embeddings: expected {len(batch)}, "
                    f"received {len(batch_embeddings)}"
                )

            embeddings.extend(batch_embeddings)

            print(
                f"  Embedded "
                f"{min(start + self.batch_size, total)}/{total}"
            )

        return embeddings

    def embed_query(self, text: str) -> List[float]:
        if not text or not str(text).strip():
            raise ValueError(
                "embed_query received empty text."
            )

        data = self._post_with_retry({
            "texts": [f"query: {str(text).strip()}"]
        })

        embeddings = data["embeddings"]

        if not embeddings:
            raise RuntimeError(
                "Embedding server returned no query embedding."
            )

        return embeddings[0]


