for index, chunk in enumerate(grandchild_chunks):
    validate_grandchild(chunk, index)

    content = safe_string(chunk["content"])
    embedding_text = safe_string(chunk["embedding_text"])

    if not content:
        skipped_empty += 1
        continue

    if not embedding_text:
        skipped_empty += 1
        continue

    valid_grandchildren.append(chunk)


